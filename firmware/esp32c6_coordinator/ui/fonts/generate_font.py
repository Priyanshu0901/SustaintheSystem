"""Regenerate the checked-in 4-bit ASCII UI font using pinned font/rasterizer inputs.

Normal firmware builds use ui_font_data.h and need no Pillow or network.
Download the locked TTF to ignored build output, then pass that path here.
"""
import hashlib
import json
from pathlib import Path
import sys

import PIL
from PIL import Image, ImageDraw, ImageFont, features


def main(source):
    folder = Path(__file__).resolve().parent
    config = json.loads((folder / "font.json").read_text())
    if hashlib.sha256(source.read_bytes()).hexdigest() != config["sha256"]:
        raise ValueError("Font differs from the pinned source")
    if PIL.__version__ != config["pillow"] or features.version("freetype2") != config["freetype"]:
        raise ValueError("Use the reviewed Pillow/FreeType versions in font.json")
    lines = ["/* Generated by fonts/generate_font.py; do not edit.",
             " * Copyright 2012 The B612 Project Authors. SIL OFL 1.1; see OFL.txt.",
             f" * Source SHA256: {config['sha256']} */", "#pragma once"]
    for index, size in enumerate(config["sizes"]):
        font = ImageFont.truetype(str(source), size=size, layout_engine=ImageFont.Layout.BASIC)
        coverage, glyphs = [], []
        for code in range(32, 127):
            char = chr(code)
            left, top, right, bottom = font.getbbox(char, anchor="ls")
            width, height = right-left, bottom-top
            offset = len(coverage)
            if width and height:
                image = Image.new("L", (width, height))
                ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
                values = [min(15, (pixel+8)//17) for pixel in image.tobytes()]
                for i in range(0, len(values), 2):
                    coverage.append((values[i] << 4) | (values[i+1] if i+1 < len(values) else 0))
            glyphs.append((offset,width,height,left,top,int(font.getlength(char)+0.5)))
        lines.append(f"static const uint8_t ui_font_bitmap_{index}[] = {{")
        for start in range(0, len(coverage), 24):
            lines.append(",".join(str(v) for v in coverage[start:start+24])+",")
        lines.append("};")
        lines.append(f"static const ui_font_glyph_t ui_font_glyphs_{index}[] = {{")
        lines.extend("{"+",".join(str(v) for v in glyph)+"}," for glyph in glyphs)
        lines.append("};")
    lines.append("static const ui_font_t ui_fonts[] = {")
    for index, size in enumerate(config["sizes"]):
        font = ImageFont.truetype(str(source), size=size)
        ascent, descent = font.getmetrics()
        lines.append(f"{{ui_font_bitmap_{index},ui_font_glyphs_{index},{ascent},{ascent+descent}}},")
    lines.append("};")
    (folder / "ui_font_data.h").write_text("\n".join(lines)+"\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
